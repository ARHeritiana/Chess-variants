#!/usr/bin/env python3
"""Regenerates app/src/main/assets/www/js/pieces-classic.js from the piece artwork bundled with python-chess
(the cburnett set by Colin M. L. Burnett, GPLv2+ / BSD / GFDL tri-licence). Colours are replaced by
placeholders so each theme can recolour the pieces: D = dark/outline, L = light, M = mid detail."""
import re, os, chess.svg as s
out = {}
for k, v in s.PIECES.items():
    v = re.sub(r'#000000|#000\b', '@D', v, flags=re.I)
    v = re.sub(r'#ffffff|#fff\b', '@L', v, flags=re.I)
    v = re.sub(r'#ececec', '@M', v, flags=re.I)
    out[k] = re.sub(r'\s+', ' ', v).strip()
dst = os.path.join(os.path.dirname(__file__), '../app/src/main/assets/www/js/pieces-classic.js')
with open(dst, 'w') as f:
    f.write('/* Generated by tools/gen_pieces.py: cburnett piece set (GPLv2+/BSD/GFDL), 45x45 viewBox, @D/@L/@M colour placeholders. */\n')
    f.write('window.PIECES_CLASSIC=' + __import__('json').dumps(out, separators=(',', ':')) + ';\n')
print(dst, os.path.getsize(dst), 'bytes')
